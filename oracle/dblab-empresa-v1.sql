CREATE TABLE DEPARTAMENTOS (
  ID_DEPARTAMENTO NUMBER(4) NOT NULL,
  NOMBRE_DEPARTAMENTO VARCHAR2(30 CHAR) NOT NULL,
  SEDE VARCHAR2(30 CHAR) NOT NULL,
  CONSTRAINT DEPARTAMENTOS_PK PRIMARY KEY (ID_DEPARTAMENTO),
  CONSTRAINT DEPARTAMENTOS_NOMBRE_UNICO UNIQUE (NOMBRE_DEPARTAMENTO)
);

CREATE TABLE EMPLEADOS (
  ID_EMPLEADO NUMBER(4) NOT NULL,
  NOMBRE VARCHAR2(40 CHAR) NOT NULL,
  APELLIDO VARCHAR2(40 CHAR) NOT NULL,
  CARGO VARCHAR2(40 CHAR) NOT NULL,
  ID_DEPARTAMENTO NUMBER(4),
  CIUDAD VARCHAR2(30 CHAR) NOT NULL,
  SALARIO NUMBER(10) NOT NULL CONSTRAINT EMPLEADOS_SALARIO_POSITIVO CHECK (SALARIO > 0),
  BONO NUMBER(10) CONSTRAINT EMPLEADOS_BONO_NO_NEGATIVO CHECK (BONO >= 0),
  FECHA_INGRESO DATE NOT NULL,
  ESTADO VARCHAR2(8 CHAR) NOT NULL CONSTRAINT EMPLEADOS_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),
  ID_JEFE NUMBER(4),
  CONSTRAINT EMPLEADOS_PK PRIMARY KEY (ID_EMPLEADO),
  CONSTRAINT EMPLEADOS_DEPARTAMENTO_FK FOREIGN KEY (ID_DEPARTAMENTO) REFERENCES DEPARTAMENTOS (ID_DEPARTAMENTO),
  CONSTRAINT EMPLEADOS_JEFE_FK FOREIGN KEY (ID_JEFE) REFERENCES EMPLEADOS (ID_EMPLEADO)
);

CREATE TABLE PROYECTOS (
  ID_PROYECTO NUMBER(4) NOT NULL,
  NOMBRE_PROYECTO VARCHAR2(40 CHAR) NOT NULL,
  ID_DEPARTAMENTO NUMBER(4) NOT NULL,
  PRESUPUESTO NUMBER(12) NOT NULL CONSTRAINT PROYECTOS_PRESUPUESTO_POSITIVO CHECK (PRESUPUESTO > 0),
  FECHA_INICIO DATE NOT NULL,
  CONSTRAINT PROYECTOS_PK PRIMARY KEY (ID_PROYECTO),
  CONSTRAINT PROYECTOS_DEPARTAMENTO_FK FOREIGN KEY (ID_DEPARTAMENTO) REFERENCES DEPARTAMENTOS (ID_DEPARTAMENTO)
);

CREATE TABLE ASIGNACIONES (
  ID_EMPLEADO NUMBER(4) NOT NULL,
  ID_PROYECTO NUMBER(4) NOT NULL,
  ROL VARCHAR2(30 CHAR) NOT NULL,
  HORAS_SEMANALES NUMBER(2) NOT NULL CONSTRAINT ASIGNACIONES_HORAS CHECK (HORAS_SEMANALES BETWEEN 1 AND 40),
  CONSTRAINT ASIGNACIONES_PK PRIMARY KEY (ID_EMPLEADO, ID_PROYECTO),
  CONSTRAINT ASIGNACIONES_EMPLEADO_FK FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT ASIGNACIONES_PROYECTO_FK FOREIGN KEY (ID_PROYECTO) REFERENCES PROYECTOS (ID_PROYECTO)
);

CREATE TABLE AUDITORIA_SALARIOS (
  ID_AUDITORIA NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ID_EMPLEADO NUMBER(4) NOT NULL,
  SALARIO_ANTERIOR NUMBER(10),
  SALARIO_NUEVO NUMBER(10),
  OPERACION VARCHAR2(10 CHAR) NOT NULL,
  FECHA_CAMBIO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT AUDITORIA_SALARIOS_PK PRIMARY KEY (ID_AUDITORIA)
);

