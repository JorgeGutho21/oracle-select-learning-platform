type TopicInput = Omit<
  CurriculumTopic,
  | 'status'
  | 'availableInLab'
  | 'availableInChallenge'
  | 'presentationScene'
  | 'lesson'
  | 'prerequisites'
> & { readonly prerequisites?: readonly string[] };

