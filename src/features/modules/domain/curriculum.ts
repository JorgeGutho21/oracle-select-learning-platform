export function levelOf(number: number): CurriculumLevel {
  const level = CURRICULUM_LEVELS.find((entry) => entry.number === number);
  if (!level) throw new Error(`Nivel desconocido: ${number}`);
  return level;
}

export function topicAnchor(topic: Pick<CurriculumTopic, 'slug'>): string {
  return `tema-${topic.slug}`;
}

export function findFutureTopic(slug: string): CurriculumTopic | undefined {
  return FUTURE_TOPICS.find((topic) => topic.slug === slug);
}

export function topicsOfLevel(number: number): readonly CurriculumTopic[] {
  return FUTURE_TOPICS.filter((topic) => topic.level === number);
}
