/**
 * Ruta académica completa (CONTENT_MAP, «Nivel actual y futuro»): el nivel 1 es la unidad
 * actual (SELECT fundamental, lecciones del Modo Estudio) y los niveles 2–7 son temas ya
 * definidos con estado «Próximamente». Es la única fuente de `/modules`, del buscador y de
 * los enlaces del laboratorio a temas futuros (`/modules#tema-<slug>`). Añadir un tema es
 * añadir una entrada: la navegación no cambia.
 *
 * Definiciones propias, verificadas con Oracle Database 19c SQL Language Reference. Los
 * ejemplos usan EMPLEADOS y, en el nivel 4, una tabla DEPARTAMENTOS que llegará con JOIN.
 */

export type LevelStage = 'AHORA' | 'SIGUIENTE NIVEL' | 'MÁS ADELANTE';
export type TopicStatus = 'current' | 'future';

export interface CurriculumLevel {
  readonly number: number;
  readonly id: string;
  readonly title: string;
  readonly stage: LevelStage;
  readonly summary: string;
  /** Progresión de ideas del nivel, por ejemplo «filas → grupos → agregación». */
  readonly progression?: string;
  readonly prerequisites: readonly number[];
}

export interface CurriculumTopic {
  readonly id: string;
  /** Ancla estable: `/modules#tema-<slug>`. */
  readonly slug: string;
  readonly title: string;
  /** Sintaxis corta para la tarjeta. */
  readonly keyword: string;
  readonly level: number;
  readonly group: string;
  readonly status: TopicStatus;
  readonly shortDefinition: string;
  readonly purpose: string;
  readonly syntax: string;
  readonly example: string;
  /** Qué hace el ejemplo sobre los datos. */
  readonly exampleNote: string;
  readonly prerequisites: readonly string[];
  readonly commonErrors: readonly string[];
  /** Estado de los datos antes y después (sentencias que modifican datos). */
  readonly before?: string;
  readonly after?: string;
  readonly warning?: string;
  readonly availableInLab: boolean;
  readonly availableInChallenge: boolean;
  /** Escena de la Exposición principal que lo presenta; solo temas actuales. */
  readonly presentationScene: string | null;
  /** Lección del Modo Estudio que lo desarrolla; solo temas actuales. */
  readonly lesson: string | null;
  /** Términos de búsqueda sin tildes. */
  readonly keywords: readonly string[];
}

